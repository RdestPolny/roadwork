/** Paint the generated medallions on their native grid when the needs HUD changes. @param {HTMLElement} root */
export function drawNeedIcons(root){
  for(const el of root.querySelectorAll('[data-need]')){
    const g=el.querySelector('canvas').getContext('2d'), colors=el.dataset.need==='hygiene'?COLORS:UPDATED_COLORS;
    ICONS[el.dataset.need].split('\n').forEach((row,y)=>{ for(let x=0;x<row.length;x++) if(row[x]!=='.'){ g.fillStyle=colors[parseInt(row[x],32)]; g.fillRect(x,y,1,1); } });
  }
}
