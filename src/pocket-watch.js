/** Draw the reference watch on a native pixel grid, with hands for the displayed minutes. @param {HTMLCanvasElement} canvas @param {number} minutes @param {boolean} [mealAvailable] */
export function drawPocketWatch(canvas,minutes,mealAvailable=false){
  const g=canvas.getContext('2d');
  g.clearRect(0,0,48,62);
  FACE.split('\n').forEach((row,y)=>{ for(let x=0;x<row.length;x++) if(row[x]!=='.'){ g.fillStyle=COLORS[parseInt(row[x],24)]; g.fillRect(x,y,1,1); } });
  const cx=24, cy=37;
  // Brass markers at VIII (breakfast) and VII (supper), lit while food is available.
  for(const hour of [8,19]){
    const a=hour/12*Math.PI*2;
    g.fillStyle=mealAvailable?'#f5cf73':'#916c39';
    g.fillRect(Math.round(cx+Math.sin(a)*17)-1,Math.round(cy-Math.cos(a)*17)-1,3,3);
  }
  // Whole-pixel strokes keep the hands as crisp as the painted face.
  const hand=(angle,length,color)=>{
    const dx=Math.sin(angle),dy=-Math.cos(angle); g.fillStyle=color;
    for(let r=-2;r<=length;r+=0.25) g.fillRect(Math.round(cx+dx*r),Math.round(cy+dy*r),1,1);
  };
  hand((minutes%720)/720*Math.PI*2,10,'#30251b');
  hand((minutes%60)/60*Math.PI*2,14,'#30251b');
  g.fillStyle='#ac7c32'; g.fillRect(cx-1,cy-1,3,3);
  g.fillStyle='#f1d28d'; g.fillRect(cx,cy,1,1);
}
